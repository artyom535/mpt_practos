# аргументов и для каждой пары выводит строку «<ключ>: <значение>».
def display_info(**kwargs):
    for key, value in kwargs.items():
        print(f"{key}: {value}")
display_info(name="Алексей", age=16, city="Москва")
# 9. Напишите функцию order, которая принимает название товара, количество (по
# умолчанию 1) и любое число дополнительных позиций. Функция возвращает строку с
# названием, количеством и списком дополнений, если они есть.
def order(product, quantity=1, *extras):
    result = f"Товар: {product}, количество: {quantity}"
    if extras:
        result += f", дополнения: {', '.join(map(str, extras))}"
    return result
print(order("Молоко", 4, "сыр", "кулебяка"))
# 10. Напишите функцию profile, которая принимает имя, возраст (по умолчанию 18) и
# любые дополнительные сведения в виде именованных аргументов. Функция
# возвращает список строк: имя, возраст и каждая дополнительная пара «ключ —
# значение».
def profile(name, age=18, **info):
    result = [f"Имя: {name}", f"Возраст: {age}"]
    for key, value in info.items():
        result.append(f"{key}: {value}")
    return result
print(profile("Тёма", 17))
print(profile("Дмитрий", 30, city="СПб", job="разработчик", hobby="калистеника"))